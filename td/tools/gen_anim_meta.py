"""Collects art/blender/meta/*.json (written by the Blender rig bakes) into anim_meta.gd. Run after baking."""
import json, glob, os
root = os.path.join(os.path.dirname(__file__), "..")
out = {}
for f in sorted(glob.glob(os.path.join(root, "art", "blender", "meta", "*.json"))):
    out[os.path.splitext(os.path.basename(f))[0]] = json.load(open(f))
def gd(v):
    if isinstance(v, dict): return "{" + ", ".join('"%s": %s' % (k, gd(x)) for k, x in v.items()) + "}"
    if isinstance(v, list): return "[" + ", ".join(gd(x) for x in v) + "]"
    if isinstance(v, str): return '"%s"' % v
    return repr(v)
with open(os.path.join(root, "anim_meta.gd"), "w") as w:
    w.write("extends RefCounted\n# GENERATED by tools/gen_anim_meta.py from art/blender/meta/*.json. Do not edit.\n")
    w.write("# counts: frames per state; strike: attack frame where the shot is released; walk_units: world units of travel per walk cycle;\n")
    w.write("# origin: frame pixel (logical 192px space) that sits on the creature's ground point; anchors: logical px offsets from origin.\n")
    w.write("const META := " + gd(out) + "\n")
print("anim_meta.gd:", list(out))
